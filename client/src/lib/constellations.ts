/** 밝기별 별 반지름(px). 작은 아이콘에서도 점이 보이게 아래 한도를 두고, 커지면 크기에 비례해요 */
export function starRadiusPx(mag: StarMag, sizePx: number): number {
  const unit = [1.0, 1.6, 2.2, 3.2][mag];
  const min = [0.6, 1.1, 1.5, 2.1][mag];
  return Math.max(min, (unit * sizePx) / 100);
}
